import { cpSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { validate, type Manifest } from "./manifest.ts";

export interface CompileResult {
  output: string;
  tabs: number;
}

const runtimeDir = join(dirname(fileURLToPath(import.meta.url)), "..", "apps-script");

function manifestsIn(artifactsDir: string): Manifest[] {
  const paths = readdirSync(artifactsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => join(artifactsDir, entry.name, "manifest.json"));

  if (paths.length === 0) paths.push(join(artifactsDir, "manifest.json"));

  return paths.map((path) => {
    const manifest = JSON.parse(readFileSync(path, "utf8")) as Manifest;
    const error = validate(manifest);
    if (error) throw new Error(`${path}: ${error}`);
    return manifest;
  });
}

function combine(manifests: Manifest[]): Manifest {
  const spreadsheetId = manifests[0]?.spreadsheet_id;
  if (!spreadsheetId) throw new Error("no manifests found");
  if (manifests.some((manifest) => manifest.spreadsheet_id !== spreadsheetId)) {
    throw new Error("all manifests must target the same spreadsheet_id");
  }

  return {
    contract_version: 1,
    spreadsheet_id: spreadsheetId,
    tabs: manifests.flatMap((manifest) => manifest.tabs),
  };
}

export function compileAppsScript(
  artifactsDir: string,
  outputDir: string,
  timezone = "Etc/UTC",
): CompileResult {
  const manifest = combine(manifestsIn(artifactsDir));

  mkdirSync(outputDir, { recursive: true });
  cpSync(join(runtimeDir, "sheetkit.js"), join(outputDir, "sheetkit.gs"));
  cpSync(join(runtimeDir, "webhook.js"), join(outputDir, "webhook.gs"));
  writeFileSync(
    join(outputDir, "manifest.gs"),
    `// Generated by sheet-kit compile. Do not edit.\nvar SHEETKIT_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 2)});\n`,
  );
  writeFileSync(join(outputDir, "appsscript.json"), JSON.stringify({
    timeZone: timezone,
    dependencies: {},
    exceptionLogging: "STACKDRIVER",
    runtimeVersion: "V8",
    webapp: { executeAs: "USER_DEPLOYING", access: "ANYONE_ANONYMOUS" },
  }, null, 2) + "\n");

  return { output: outputDir, tabs: manifest.tabs.length };
}
