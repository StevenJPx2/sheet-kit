// The compiler. Given resolved manifests, it assembles an Apps Script project
// from the runtime core + ONLY the primitives those manifests use, generates
// the render-dispatch list, and embeds the manifest. Nothing is hand-copied:
// unused features (e.g. charts) never appear in the output.

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { validate } from "./validate.js";
import { PRIMITIVES } from "../primitives/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const runtimeDir = join(here, "..", "runtime");

/**
 * @param {string} artifactsDir
 * @returns {import("../types.js").Manifest[]}
 */
function manifestsIn(artifactsDir) {
  const paths = readdirSync(artifactsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => join(artifactsDir, entry.name, "manifest.json"));
  if (paths.length === 0) paths.push(join(artifactsDir, "manifest.json"));
  return paths.map((path) => JSON.parse(readFileSync(path, "utf8")));
}

/** @param {import("../types.js").Manifest[]} manifests */
function combine(manifests) {
  const spreadsheetId = manifests[0]?.spreadsheet_id;
  if (!spreadsheetId) throw new Error("no manifests found");
  if (manifests.some((m) => m.spreadsheet_id !== spreadsheetId)) {
    throw new Error("all manifests must target the same spreadsheet_id");
  }
  return {
    contract_version: 1,
    spreadsheet_id: spreadsheetId,
    tabs: manifests.flatMap((m) => m.tabs),
  };
}

/** A tab uses a primitive when its field is present and non-empty. */
function tabUses(tab, field) {
  const v = tab[field];
  return Array.isArray(v) ? v.length > 0 : v != null;
}

/**
 * Compile every manifest under artifactsDir into an Apps Script project.
 * @param {string} artifactsDir
 * @param {string} outputDir
 * @param {string} [timezone]
 * @returns {{ output: string, tabs: number, primitives: string[] }}
 */
export function compileAppsScript(artifactsDir, outputDir, timezone = "Etc/UTC") {
  const manifest = combine(manifestsIn(artifactsDir));
  const err = validate(manifest);
  if (err) throw new Error(err);

  const used = PRIMITIVES
    .filter((p) => p.field === null || manifest.tabs.some((t) => tabUses(t, p.field)))
    .sort((a, b) => a.order - b.order);

  const core = readFileSync(join(runtimeDir, "core.js"), "utf8");
  const webhook = readFileSync(join(runtimeDir, "webhook.js"), "utf8");
  const primitivesSrc = used.map((p) => `// primitive: ${p.name} (field: ${p.field ?? "always"})\n${p.runtime}`).join("\n\n");
  const steps = `var SK_RENDER_STEPS = [${used.map((p) => p.fn).join(", ")}];`;

  const sheetkitGs = [
    "// Generated by sheet-kit compile. Do not edit — author src/primitives/*.js instead.",
    core.trimEnd(),
    primitivesSrc,
    steps,
  ].join("\n\n") + "\n";

  mkdirSync(outputDir, { recursive: true });
  writeFileSync(join(outputDir, "sheetkit.gs"), sheetkitGs);
  writeFileSync(join(outputDir, "webhook.gs"), "// Generated by sheet-kit compile. Do not edit.\n\n" + webhook.trimEnd() + "\n");
  writeFileSync(
    join(outputDir, "manifest.gs"),
    `// Generated by sheet-kit compile. Do not edit.\nvar SHEETKIT_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 2)});\n`,
  );
  writeFileSync(join(outputDir, "appsscript.json"), JSON.stringify({
    timeZone: timezone,
    dependencies: {},
    exceptionLogging: "STACKDRIVER",
    runtimeVersion: "V8",
    webapp: { executeAs: "USER_DEPLOYING", access: "ANYONE_ANONYMOUS" },
  }, null, 2) + "\n");

  return { output: outputDir, tabs: manifest.tabs.length, primitives: used.map((p) => p.name) };
}
